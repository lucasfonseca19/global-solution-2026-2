import {test,expect} from '@playwright/test';
test('registro: prévia, erros, confirmação, continuidade, zero e consulta', async ({page})=>{
 await page.goto('/');
 await page.getByLabel('Login',{exact:true}).fill('demo');
 await page.getByLabel('Senha',{exact:true}).fill('merenda-demo');
 await page.getByRole('button',{name:'Entrar na demonstração'}).click();
 await page.getByRole('button',{name:'Registrar descarte',exact:true}).click();
 await expect(page.getByText('15/11/2026 · hoje',{exact:true})).toBeVisible();
 await expect(page.getByRole('textbox',{name:'Data do serviço'})).toHaveCount(0);
 await page.getByRole('button',{name:'Procurar serviço'}).click();
 await expect(page.getByText('Novo serviço.',{exact:false})).toBeVisible();
 await expect(page.getByRole('button',{name:'Simular: Lixeira da cozinha'})).toHaveCount(0);
 await page.getByRole('button',{name:'Abrir simulação'}).click();
 await page.getByRole('button',{name:'Simular: Lixeira da cozinha'}).click();
 await expect(page.getByText('Total parcial: 0,00 kg',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Simular: Etiqueta desconhecida'}).click();
 await expect(page.getByText('Lixeira não reconhecida. Repita a leitura.')).toBeVisible();
 await expect(page.getByRole('button',{name:'Confirmar pesagem'})).toHaveCount(0);
 await page.getByRole('button',{name:'Simular: Peso abaixo da tara'}).click();
 await expect(page.getByText('Peso bruto menor que a tara ou inválido. Repita a leitura.')).toBeVisible();
 await page.getByRole('button',{name:'Simular: Lixeira da cozinha'}).click();
 await page.getByRole('button',{name:'Confirmar pesagem'}).click();
 await expect(page.getByText('Total parcial: 3,00 kg',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Procurar serviço'}).click();
 await expect(page.getByText('Serviço encontrado. Continue suas pesagens.')).toBeVisible();
 await page.getByRole('button',{name:'Simular: Lixeira dos pratos'}).click();
 await expect(page.getByText('Total parcial: 3,00 kg',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Confirmar pesagem'}).click();
 await expect(page.getByText('Total confirmado: 5,00 kg',{exact:true})).toBeVisible();
 await page.screenshot({path:'test-results/registro-completo.png',fullPage:true});
 await page.getByRole('button',{name:'Simular: Pratos sem descarte'}).click();
 await page.getByLabel('Tipo de refeição',{exact:true}).fill('Jantar');
 await expect(page.getByRole('button',{name:'Confirmar pesagem'})).toHaveCount(0);
 await page.getByLabel('Tipo de refeição',{exact:true}).fill('Almoço');
 await page.getByRole('button',{name:'Procurar serviço'}).click();
 await page.getByRole('button',{name:'Simular: Pratos sem descarte'}).click();
 await page.getByRole('button',{name:'Atualizar pesagem'}).click();
 await expect(page.getByText('Total confirmado: 3,00 kg',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Ver detalhes do serviço'}).click();
 await expect(page.getByText('0,00 kg',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Voltar ao histórico'}).click();
 await expect(page.getByRole('button',{name:/15\/11\/2026.*Total: 3,00 kg/})).toHaveCount(1);
});

// Cada teste começa com armazenamento próprio vazio; recargas dentro do teste preservam dados.
test.beforeEach(async ({page}) => {
 await page.clock.setFixedTime(new Date(2026,10,15,12));
 await page.goto('/');
 await page.evaluate(() => localStorage.clear());
 await page.reload();
});
