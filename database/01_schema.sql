-- ---------------------------------------------------------------------
-- USUARIO: funcionário que entra no app e registra as pesagens.
-- A senha nunca é guardada em texto puro, somente o hash BCrypt.
-- ---------------------------------------------------------------------
CREATE TABLE usuario (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nome        VARCHAR(100) NOT NULL,
    login       VARCHAR(50)  NOT NULL,
    senha_hash  VARCHAR(100) NOT NULL,
    criado_em   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_usuario PRIMARY KEY (id),
    CONSTRAINT uk_usuario_login UNIQUE (login),
    CONSTRAINT ck_usuario_login CHECK (login ~ '^[a-z0-9._-]{3,50}$'),
    CONSTRAINT ck_usuario_hash CHECK (senha_hash LIKE '$2%')
);

-- ---------------------------------------------------------------------
-- CATEGORIA_DESCARTE: os dois tipos de descarte medidos.
--   SOBRA_DESCARTADA: preparado e não servido, que será descartado.
--   RESTO_PRATO: restos comestíveis devolvidos nos pratos.
-- ---------------------------------------------------------------------
CREATE TABLE categoria_descarte (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    codigo     VARCHAR(30)  NOT NULL,
    descricao  VARCHAR(150) NOT NULL,
    CONSTRAINT pk_categoria_descarte PRIMARY KEY (id),
    CONSTRAINT uk_categoria_codigo UNIQUE (codigo),
    CONSTRAINT ck_categoria_codigo CHECK (codigo ~ '^[A-Z_]+$')
);

-- ---------------------------------------------------------------------
-- LIXEIRA: recipiente com etiqueta RFID, categoria fixa e tara (peso vazio).
-- A tara é descontada automaticamente do peso lido na balança.
-- ---------------------------------------------------------------------
CREATE TABLE lixeira (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    codigo_rfid   VARCHAR(40)   NOT NULL,
    descricao     VARCHAR(100)  NOT NULL,
    categoria_id  BIGINT        NOT NULL,
    tara_kg       NUMERIC(7,3)  NOT NULL,
    CONSTRAINT pk_lixeira PRIMARY KEY (id),
    CONSTRAINT uk_lixeira_rfid UNIQUE (codigo_rfid),
    -- Permite que a pesagem referencie (lixeira, categoria) e garanta coerência.
    CONSTRAINT uk_lixeira_id_categoria UNIQUE (id, categoria_id),
    CONSTRAINT fk_lixeira_categoria FOREIGN KEY (categoria_id)
        REFERENCES categoria_descarte (id),
    CONSTRAINT ck_lixeira_tara CHECK (tara_kg >= 0 AND tara_kg <= 100)
);

-- ---------------------------------------------------------------------
-- SERVICO_ALIMENTACAO: uma refeição servida pela escola em uma data
-- (ex.: almoço de 12/11). Só pode existir um por data e tipo de refeição.
-- ---------------------------------------------------------------------
CREATE TABLE servico_alimentacao (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    data_servico    DATE         NOT NULL,
    tipo_refeicao   VARCHAR(30)  NOT NULL,
    usuario_id      BIGINT       NOT NULL,
    criado_em       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    concluido_em    TIMESTAMPTZ,
    CONSTRAINT pk_servico_alimentacao PRIMARY KEY (id),
    CONSTRAINT uk_servico_data_tipo UNIQUE (data_servico, tipo_refeicao),
    CONSTRAINT fk_servico_usuario FOREIGN KEY (usuario_id)
        REFERENCES usuario (id),
    CONSTRAINT ck_servico_tipo CHECK (LENGTH(TRIM(tipo_refeicao)) > 0)
);

-- ---------------------------------------------------------------------
-- PESAGEM: uma contribuição individual confirmada. Várias contribuições
-- da mesma categoria somam; correção altera somente o registro selecionado.
-- A tara usada fica registrada, para o histórico não mudar se a lixeira
-- for trocada ou recalibrada no futuro.
-- ---------------------------------------------------------------------
CREATE TABLE pesagem (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    servico_id        BIGINT        NOT NULL,
    lixeira_id        BIGINT        NOT NULL,
    categoria_id      BIGINT        NOT NULL,
    peso_bruto_kg     NUMERIC(7,3)  NOT NULL,
    tara_kg           NUMERIC(7,3)  NOT NULL,
    peso_liquido_kg   NUMERIC(7,3)  NOT NULL,
    confirmado_em     TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_pesagem PRIMARY KEY (id),
    -- Excluir o serviço remove suas pesagens.
    CONSTRAINT fk_pesagem_servico FOREIGN KEY (servico_id)
        REFERENCES servico_alimentacao (id) ON DELETE CASCADE,
    -- A categoria precisa ser a mesma da lixeira usada.
    CONSTRAINT fk_pesagem_lixeira_categoria FOREIGN KEY (lixeira_id, categoria_id)
        REFERENCES lixeira (id, categoria_id),
    CONSTRAINT ck_pesagem_tara CHECK (tara_kg >= 0 AND tara_kg <= 100),
    CONSTRAINT ck_pesagem_bruto CHECK (peso_bruto_kg >= tara_kg AND peso_bruto_kg <= 500),
    CONSTRAINT ck_pesagem_liquido CHECK (peso_liquido_kg = peso_bruto_kg - tara_kg)
);

CREATE INDEX ix_servico_data ON servico_alimentacao (data_servico);
CREATE INDEX ix_pesagem_lixeira ON pesagem (lixeira_id);

-- Cada ciclo registra o hash SHA-256 do pedido canônico, inclusive correções.
-- O serviço aplica repetição sem nova escrita e rejeita hash diferente.
CREATE TABLE ciclo_pesagem (
    ciclo_id VARCHAR(100) NOT NULL,
    payload_hash VARCHAR(64) NOT NULL,
    servico_id BIGINT,
    CONSTRAINT pk_ciclo_pesagem PRIMARY KEY (ciclo_id),
    CONSTRAINT ck_ciclo_id CHECK (LENGTH(TRIM(ciclo_id)) > 0),
    CONSTRAINT ck_ciclo_hash CHECK (payload_hash ~ '^[a-f0-9]{64}$'),
    CONSTRAINT fk_ciclo_servico FOREIGN KEY (servico_id)
        REFERENCES servico_alimentacao(id) ON DELETE SET NULL
);
CREATE INDEX ix_pesagem_servico ON pesagem(servico_id);
CREATE INDEX ix_ciclo_servico ON ciclo_pesagem(servico_id);

